func TestQuote(t *testing.T) {
	tests := []struct{ in, want string }{
		{"", ""},
		{"dev", "dev"},
		{"http://localhost:5173,http://127.0.0.1:5173", "http://localhost:5173,http://127.0.0.1:5173"},
		{"aGVsbG8=", "aGVsbG8="},
		{"has space", "'has space'"},
		{"a#b", "'a#b'"},
		{"$HOME", "'$HOME'"},
		{`back\slash`, `'back\slash'`},
		{`say "hi"`, `'say "hi"'`},
		{"it's", `"it's"`},
		{"line1\nline2", `"line1\nline2"`},
		{`it's "q" \ x`, `"it's \"q\" \\ x"`},
	}
	for _, tt := range tests {
		if got := Quote(tt.in); got != tt.want {
			t.Errorf("Quote(%q) = %s, want %s", tt.in, got, tt.want)
		}
	}
}

var awkward = []Pair{
	{"EMPTY", ""},
	{"PLAIN", "value"},
	{"SPACES", "  leading and trailing  "},
	{"HASH", "a #not-a-comment"},
	{"DOLLAR", "$NOT_EXPANDED ${X}"},
	{"SINGLE", "it's"},
	{"DOUBLE", `"quoted"`},
	{"BOTH", `it's "both"`},
	{"BACKSLASH", `C:\path\to\n`},
	{"MULTILINE", "-----BEGIN KEY-----\nabc\n-----END KEY-----\n"},
	{"CRLF", "a\r\nb"},
	{"UNICODE", "héllo — 世界 🚚"},
	{"EQUALS", "a=b=c"},
	{"JSON", `{"a":[1,2],"b":"it's"}`},
}

func TestRoundTrip(t *testing.T) {
	data := Render([]string{"Generated by envhaul", "do not edit"}, awkward)
	got, err := Parse(data)
	if err != nil {
		t.Fatalf("Parse: %v\n%s", err, data)
	}
	if !reflect.DeepEqual(got, awkward) {
		t.Errorf("round trip mismatch\nrendered:\n%s\n got: %q\nwant: %q", data, got, awkward)
	}
}

func TestParseHandWritten(t *testing.T) {
	src := `
# comment
export A=1
B = two   # trailing comment
C="multi
line"
D='single # not comment'
E="esc \"q\" \$x \t"
`
	got, err := Parse([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	want := []Pair{
		{"A", "1"},
		{"B", "two"},
		{"C", "multi\nline"},
		{"D", "single # not comment"},
		{"E", "esc \"q\" $x \t"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("got %q\nwant %q", got, want)
	}
}

func TestParseErrors(t *testing.T) {
	for _, src := range []string{"NOEQUALS\n", "1BAD=x\n", "A=\"unterminated\n"} {
		if _, err := Parse([]byte(src)); err == nil {
			t.Errorf("Parse(%q): expected error", src)
		}
	}
}

func TestWriteFile(t *testing.T) {
	path := filepath.Join(t.TempDir(), "nested", "dir", ".env")
	changed, err := WriteFile(path, []byte("A=1\n"))
	if err != nil || !changed {
		t.Fatalf("first write: changed=%v err=%v", changed, err)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if runtime.GOOS != "windows" && info.Mode().Perm() != 0o600 {
		t.Errorf("mode = %v, want 0600", info.Mode().Perm())
	}
	changed, err = WriteFile(path, []byte("A=1\n"))
	if err != nil || changed {
		t.Errorf("identical write: changed=%v err=%v", changed, err)
	}
	changed, err = WriteFile(path, []byte("A=2\n"))
	if err != nil || !changed {
		t.Errorf("changed write: changed=%v err=%v", changed, err)
	}
	if b, _ := os.ReadFile(path); string(b) != "A=2\n" {
		t.Errorf("content = %q", b)
	}
	entries, _ := os.ReadDir(filepath.Dir(path))
	if len(entries) != 1 {
		t.Errorf("temp files left behind: %v", entries)
	}
}

func FuzzRoundTrip(f *testing.F) {
	for _, p := range awkward {
		f.Add(p.Value)
	}
	f.Fuzz(func(t *testing.T, v string) {
		data := Render(nil, []Pair{{"K", v}})
		got, err := Parse(data)
		if err != nil {
			t.Fatalf("Parse(Render(%q)) error: %v\n%s", v, err, data)
		}
		if len(got) != 1 || got[0].Value != v {
			t.Fatalf("round trip of %q gave %q", v, got)
		}
	})
}
