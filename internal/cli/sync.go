package cli

import (
	"context"
	"fmt"
	"path/filepath"
	"text/tabwriter"

	"github.com/spf13/cobra"

	"github.com/davidtucker/envhaul/internal/config"
	"github.com/davidtucker/envhaul/internal/dotenv"
	"github.com/davidtucker/envhaul/internal/gitcheck"
	"github.com/davidtucker/envhaul/internal/resolve"
)

func (a *app) syncCmd() *cobra.Command {
	var strict bool
	cmd := &cobra.Command{
		Use:   "sync [component...]",
		Short: "Fetch values and write .env files",
		Long: `Resolve every variable and write each component's env file (all components,
or only those named).

Nothing is written unless every component resolves. Files are written
atomically with mode 0600 and left untouched when their content is unchanged.
Referenced values that do not exist are written as empty strings with a
warning; use --strict to fail instead.`,
		Example: `  envhaul sync
  envhaul sync api frontend
  envhaul -c envhaul.staging.yaml sync --strict`,
		ValidArgsFunction: a.completeComponents,
		RunE: func(cmd *cobra.Command, args []string) error {
			cfg, comps, resolved, err := a.resolve(cmd.Context(), args, strict)
			if err != nil {
				return err
			}

			tw := tabwriter.NewWriter(a.opts.Stdout, 0, 0, 2, ' ', 0)
			var notIgnored []string
			for i, rc := range resolved {
				path := cfg.EnvFilePath(comps[i])
				changed, err := dotenv.WriteFile(path, render(cfg, rc))
				if err != nil {
					return fmt.Errorf("writing %s: %w", relPath(path), err)
				}
				status := a.paint(a.opts.Stdout, "32", "wrote")
				if !changed {
					status = a.paint(a.opts.Stdout, "2", "unchanged")
				}
				fmt.Fprintf(tw, "%s\t%s\t(%s)\n", status, relPath(path), plural(len(rc.Values), "var"))
				if gitcheck.Check(path) == gitcheck.NotIgnored {
					notIgnored = append(notIgnored, relPath(path))
				}
			}
			if err := tw.Flush(); err != nil {
				return err
			}
			for _, p := range notIgnored {
				a.warnf("%s is not ignored by git; add it to .gitignore so secrets are not committed", p)
			}
			return nil
		},
	}
	cmd.Flags().BoolVar(&strict, "strict", false, "fail if any referenced value does not exist")
	return cmd
}

// resolve loads the config, selects components and resolves them, printing
// missing-value warnings.
func (a *app) resolve(ctx context.Context, names []string, strict bool) (*config.Config, []*config.Component, []*resolve.Component, error) {
	cfg, err := a.loadConfig()
	if err != nil {
		return nil, nil, nil, err
	}
	comps, err := cfg.Select(names)
	if err != nil {
		return nil, nil, nil, err
	}
	r := &resolve.Resolver{Registry: a.registry(cfg), Strict: strict}
	resolved, missing, err := r.Resolve(ctx, comps)
	if err != nil {
		return nil, nil, nil, err
	}
	a.reportMissing(missing)
	return cfg, comps, resolved, nil
}

func (a *app) reportMissing(missing []resolve.Missing) {
	if len(missing) == 0 {
		return
	}
	a.warnf("%s not found and written as empty (use --strict to fail, or |default:value):", plural(len(missing), "referenced value"))
	for _, m := range missing {
		fmt.Fprintf(a.opts.Stderr, "  %s\n", m)
	}
}

func header(cfg *config.Config, comp *config.Component) []string {
	src := filepath.Base(cfg.Path)
	if cfg.Name != "" {
		src += " (" + cfg.Name + ")"
	}
	return []string{
		"Generated by envhaul from " + src + ". Do not edit; changes are overwritten.",
		"Regenerate with: envhaul sync " + comp.Name,
	}
}

func render(cfg *config.Config, rc *resolve.Component) []byte {
	pairs := make([]dotenv.Pair, len(rc.Values))
	for i, v := range rc.Values {
		pairs[i] = dotenv.Pair{Key: v.Name, Value: v.Value}
	}
	return dotenv.Render(header(cfg, rc.Component), pairs)
}

func plural(n int, word string) string {
	if n == 1 {
		return fmt.Sprintf("1 %s", word)
	}
	return fmt.Sprintf("%d %ss", n, word)
}
